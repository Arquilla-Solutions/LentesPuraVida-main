// Packs admin/ (the order board page, script and styles) into a module the /admin function
// serves after the login check. The board is never a public static file, so no path trick
// (/admin%2f..., //admin/..., /%61dmin/...) can reach it around the check.
// Run by `npm run build`; tests/admin-assets.test.ts fails if the packed copy is out of date.
import { readFileSync, writeFileSync } from "node:fs";

const FILES = { "index.html": "text/html", "board.js": "text/javascript", "board.css": "text/css" };
export const OUT = new URL("../functions/_lib/admin-assets.gen.ts", import.meta.url);

export function render() {
  const entries = Object.entries(FILES).map(([name, type]) => {
    const body = readFileSync(new URL(`../admin/${name}`, import.meta.url), "utf8");
    return `  ${JSON.stringify(name)}: { type: ${JSON.stringify(`${type}; charset=utf-8`)}, body: ${JSON.stringify(body)} },`;
  });
  return `// Generated by scripts/admin-assets.mjs from admin/. Do not edit by hand.\n` +
    `export const ADMIN_ASSETS: Record<string, { type: string; body: string }> = {\n${entries.join("\n")}\n};\n`;
}

if (import.meta.url === `file://${process.argv[1]}`) writeFileSync(OUT, render());
